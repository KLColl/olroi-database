BEGIN;

CREATE TABLE bookstore.app_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE
        CHECK (username ~ '^[a-z0-9_.-]{3,40}$'),
    password_hash TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE
        CHECK (
            email = LOWER(TRIM(email))
            AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
        ),
    role TEXT NOT NULL DEFAULT 'reader'
        CHECK (role IN ('admin', 'manager', 'reader')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    api_token_hash TEXT UNIQUE
        CHECK (api_token_hash IS NULL OR api_token_hash ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE bookstore.activity_log
ADD CONSTRAINT activity_log_user_fk
FOREIGN KEY (user_id)
REFERENCES bookstore.app_users (user_id)
ON DELETE SET NULL;

CREATE TRIGGER app_users_audit
AFTER INSERT OR UPDATE OR DELETE ON bookstore.app_users
FOR EACH ROW
EXECUTE FUNCTION bookstore.audit_data_change('user_id');

COMMIT;
