BEGIN;
CREATE SCHEMA bookstore;
CREATE TABLE bookstore.authors (
    author_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL CHECK (LENGTH(TRIM(first_name)) > 0),
    last_name TEXT NOT NULL CHECK (LENGTH(TRIM(last_name)) > 0),
    country TEXT NOT NULL CHECK (LENGTH(TRIM(country)) > 0)
);
CREATE TABLE bookstore.categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE CHECK (LENGTH(TRIM(category_name)) > 0),
    description TEXT
);
CREATE TABLE bookstore.books (
    book_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn VARCHAR(13) NOT NULL UNIQUE CHECK (isbn ~ '^[0-9]{13}$'),
    title TEXT NOT NULL CHECK (LENGTH(TRIM(title)) > 0),
    author_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    publication_year INTEGER NOT NULL CHECK (publication_year BETWEEN 1450 AND 2100),
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    CONSTRAINT books_author_fk FOREIGN KEY(author_id) REFERENCES bookstore.authors
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT books_category_fk FOREIGN KEY(category_id) REFERENCES bookstore.categories
        ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE bookstore.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL CHECK (LENGTH(TRIM(full_name)) > 0),
    email TEXT NOT NULL UNIQUE CHECK (email=LOWER(TRIM(email))
        AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    phone VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE bookstore.orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Confirmed','Cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,
    CONSTRAINT orders_customer_fk FOREIGN KEY(customer_id) REFERENCES bookstore.customers
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT orders_confirmation_check CHECK (
        (status='Draft' AND confirmed_at IS NULL)
        OR (status='Confirmed' AND confirmed_at IS NOT NULL) OR status='Cancelled'),
    CONSTRAINT orders_dates_check CHECK(confirmed_at IS NULL OR confirmed_at>=created_at)
);
CREATE TABLE bookstore.order_items (
    order_id BIGINT NOT NULL,
    book_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL CHECK(quantity>0),
    unit_price NUMERIC(10,2) NOT NULL CHECK(unit_price>=0),
    PRIMARY KEY(order_id,book_id),
    CONSTRAINT order_items_order_fk FOREIGN KEY(order_id) REFERENCES bookstore.orders
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT order_items_book_fk FOREIGN KEY(book_id) REFERENCES bookstore.books
        ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMIT;
